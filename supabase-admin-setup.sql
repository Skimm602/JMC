-- The maintenance page writes through this rather than updating the row
-- directly, so "who may change stock" is answered in one place.
create or replace function public.set_product_stock(p_model text, p_stock integer)
returns boolean language plpgsql security definer
set search_path = public, pg_temp as $$
begin
  if not public.is_admin() then return false; end if;
  if p_stock is null or p_stock < 0 then
    raise exception 'Stock cannot be negative.' using errcode = 'check_violation';
  end if;

  update public.products
     set stock = p_stock, updated_at = now()
   where model = p_model;

  return found;
end;
$$;


-- ===========================================================================
-- 3. ORDERS
--    Admin-only for now: nothing on the public site creates one. Rows are
--    entered here or seeded, and the panel approves or rejects them.
-- ===========================================================================

create table if not exists public.orders (
  id              uuid primary key default gen_random_uuid(),
  reference       text unique,
  customer_id     uuid references auth.users (id) on delete set null,
  customer_name   text not null,
  customer_email  text,
  customer_phone  text,
  notes           text,
  status          text not null default 'pending'
                    check (status in ('pending', 'approved', 'rejected')),
  rejection_reason text,
  placed_at       timestamptz not null default now(),
  reviewed_at     timestamptz,
  reviewed_by     uuid references auth.users (id)
);

create table if not exists public.order_items (
  id          uuid primary key default gen_random_uuid(),
  order_id    uuid not null references public.orders (id) on delete cascade,
  -- The model is stored rather than a foreign key to products: an order is a
  -- record of what was agreed, and it must not change shape when the
  -- catalogue does.
  model       text not null,
  description text,
  quantity    integer not null check (quantity > 0),
  unit_price  numeric(12,2)
);

create index if not exists order_items_order_id_idx on public.order_items (order_id);
create index if not exists orders_status_idx        on public.orders (status, placed_at);

-- A readable number for the phone: ORD-000001.
create sequence if not exists public.order_reference_seq;

create or replace function public.orders_set_reference()
returns trigger language plpgsql as $$
begin
  if new.reference is null then
    new.reference := 'ORD-' || lpad(nextval('public.order_reference_seq')::text, 6, '0');
  end if;
  return new;
end;
$$;

drop trigger if exists orders_set_reference on public.orders;
create trigger orders_set_reference
  before insert on public.orders
  for each row execute function public.orders_set_reference();

