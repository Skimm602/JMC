-- ===========================================================================
-- 1. ADMINS
--    Your table, keyed by email — `id` is a counter, not the user's uuid, and
--    auth.users.email is unique, so email identifies a person just as well.
-- ===========================================================================

do $$
begin
  if not exists (
    select 1 from information_schema.columns
     where table_schema = 'public' and table_name = 'admins' and column_name = 'id'
       and (is_identity = 'YES' or column_default is not null)
  ) then
    alter table public.admins alter column id add generated by default as identity;
  end if;
end
$$;

create unique index if not exists admins_email_lower_key on public.admins (lower(email));

alter table public.admins enable row level security;

-- No direct writes from a browser. Without this, any signed-in customer could
-- insert their own email with the public anon key and become an admin.
revoke all on public.admins from anon, authenticated;
grant select on public.admins to authenticated;

-- Whoever is already an admin moves across BEFORE anything reads the new
-- table. Without this you lock yourself out when is_admin is dropped below.
insert into public.admins (name, email)
select p.full_name, u.email
from public.profiles p
join auth.users u on u.id = p.id
where p.is_admin
on conflict (lower(email)) do nothing;

create or replace function public.is_admin()
returns boolean language sql stable security definer
set search_path = public, pg_temp as $$
  select exists (
    select 1 from auth.users u
    join public.admins a on lower(a.email) = lower(u.email)
    where u.id = auth.uid()
  )
$$;

create or replace function public.admin_exists()
returns boolean language sql stable security definer
set search_path = public, pg_temp as $$
  select exists (select 1 from public.admins)
$$;

-- The accounts page needs to know which uuids are admins. Guarded.
create or replace function public.admin_user_ids()
returns setof uuid language plpgsql stable security definer
set search_path = public, pg_temp as $$
begin
  if not public.is_admin() then return; end if;
  return query
    select u.id from auth.users u
    join public.admins a on lower(a.email) = lower(u.email);
end;
$$;

drop policy if exists "Admins read the roster" on public.admins;
create policy "Admins read the roster" on public.admins
  for select to authenticated using (public.is_admin());

-- /admin/register — the "save it here" step. Open by design.
create or replace function public.grant_admin_on_register()
returns boolean language plpgsql security definer
set search_path = public, pg_temp as $$
declare v_uid uuid := auth.uid();
begin
  if v_uid is null then return false; end if;
  insert into public.admins (name, email)
  select p.full_name, u.email
  from auth.users u left join public.profiles p on p.id = u.id
  where u.id = v_uid
  on conflict (lower(email)) do nothing;
  return true;
end;
$$;

-- /admin/setup — an existing account, on a site with no admin yet.
create or replace function public.claim_first_admin()
returns boolean language plpgsql security definer
set search_path = public, pg_temp as $$
declare v_uid uuid := auth.uid();
begin
  if v_uid is null then return false; end if;
  perform pg_advisory_xact_lock(hashtext('claim_first_admin'));
  if exists (select 1 from public.admins) then return false; end if;
  insert into public.admins (name, email)
  select p.full_name, u.email
  from auth.users u left join public.profiles p on p.id = u.id
  where u.id = v_uid
  on conflict (lower(email)) do nothing;
  return true;
end;
$$;

-- The Make admin / Remove admin buttons.
create or replace function public.set_admin(p_target uuid, p_value boolean)
returns boolean language plpgsql security definer
set search_path = public, pg_temp as $$
declare v_uid uuid := auth.uid(); v_email text;
begin
  if v_uid is null or not public.is_admin() then return false; end if;
  if p_target = v_uid and not p_value then
    raise exception 'You cannot remove your own admin access.' using errcode = 'check_violation';
  end if;

  select u.email into v_email from auth.users u where u.id = p_target;
  if v_email is null then return false; end if;

  if p_value then
    insert into public.admins (name, email)
    select p.full_name, v_email from public.profiles p where p.id = p_target
    on conflict (lower(email)) do nothing;
  else
    delete from public.admins where lower(email) = lower(v_email);
  end if;
  return true;
end;
$$;

-- The last two things reading profiles.is_admin, then the column goes.
drop policy if exists "Admins can view all verification docs" on storage.objects;
create policy "Admins can view all verification docs" on storage.objects
  for select to authenticated
  using (bucket_id = 'verification-docs' and public.is_admin());

create or replace function public.profiles_guard_privileged_columns()
returns trigger language plpgsql as $$
begin
  if current_user in ('postgres', 'service_role', 'supabase_admin') or public.is_admin() then
    return new;
  end if;

  if tg_op = 'INSERT' then
    new.verification_status :=
      case when new.customer_type = 'installer' then 'pending' else 'not_required' end;
  else
    if new.verification_status is distinct from old.verification_status
       and new.verification_status <> 'pending' then
      new.verification_status := old.verification_status;
    end if;
  end if;
  return new;
end;
$$;

