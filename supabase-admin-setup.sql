-- ---------------------------------------------------------------------------
-- Approving takes the stock off the shelf, in the same transaction as the
-- status change. If any line is short, the whole approval fails and says so —
-- an approved order the warehouse cannot fill is worse than a refused one.
-- ---------------------------------------------------------------------------
create or replace function public.approve_order(p_order uuid)
returns boolean language plpgsql security definer
set search_path = public, pg_temp as $$
declare
  v_uid  uuid := auth.uid();
  v_item record;
  v_have integer;
begin
  if not public.is_admin() then return false; end if;

  if not exists (select 1 from public.orders where id = p_order and status = 'pending') then
    raise exception 'That order is not awaiting review.' using errcode = 'check_violation';
  end if;

  for v_item in
    select i.model, sum(i.quantity) as qty
    from public.order_items i
    where i.order_id = p_order
    group by i.model
  loop
    select p.stock into v_have from public.products p where p.model = v_item.model for update;

    if v_have is null then
      raise exception 'No product called % is in the catalogue.', v_item.model
        using errcode = 'check_violation';
    end if;

    if v_have < v_item.qty then
      raise exception 'Only % of % left in stock, and the order asks for %.',
        v_have, v_item.model, v_item.qty using errcode = 'check_violation';
    end if;

    update public.products
       set stock = stock - v_item.qty, updated_at = now()
     where model = v_item.model;
  end loop;

  update public.orders
     set status = 'approved', reviewed_at = now(), reviewed_by = v_uid, rejection_reason = null
   where id = p_order;

  return true;
end;
$$;

create or replace function public.reject_order(p_order uuid, p_reason text)
returns boolean language plpgsql security definer
set search_path = public, pg_temp as $$
begin
  if not public.is_admin() then return false; end if;

  if coalesce(btrim(p_reason), '') = '' then
    raise exception 'A reason is required to reject an order.' using errcode = 'check_violation';
  end if;

  if not exists (select 1 from public.orders where id = p_order and status = 'pending') then
    raise exception 'That order is not awaiting review.' using errcode = 'check_violation';
  end if;

  -- Nothing to give back: stock only moves on approval.
  update public.orders
     set status = 'rejected', reviewed_at = now(), reviewed_by = auth.uid(),
         rejection_reason = btrim(p_reason)
   where id = p_order;

  return true;
end;
$$;


-- ===========================================================================
-- 4. DELETING AN ACCOUNT
--    Removes the auth user and everything hanging off it. Irreversible, so it
--    refuses on the one case that cannot be undone by making a new account:
--    deleting yourself.
-- ===========================================================================
create or replace function public.delete_user_account(p_target uuid)
returns boolean language plpgsql security definer
set search_path = public, pg_temp as $$
declare v_uid uuid := auth.uid(); v_email text;
begin
  if v_uid is null or not public.is_admin() then return false; end if;
  if p_target = v_uid then
    raise exception 'You cannot delete your own account.' using errcode = 'check_violation';
  end if;

  select u.email into v_email from auth.users u where u.id = p_target;
  if v_email is null then return false; end if;

  delete from public.installer_verifications where profile_id = p_target;
  delete from public.admins  where lower(email) = lower(v_email);
  delete from public.profiles where id = p_target;
  delete from auth.users     where id = p_target;

  -- Any verification documents they uploaded stay in the storage bucket under
  -- their uuid; SQL cannot reach object storage. Clear them from
  -- Storage -> verification-docs if it matters.
  return true;
end;
$$;


